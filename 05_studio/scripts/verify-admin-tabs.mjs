import {chromium,expect} from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const dir='../artifacts/owner-workbench/tab-cache';await fs.mkdir(dir,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const results=[];
try{
 for(const viewport of [{width:390,height:844},{width:320,height:568},{width:844,height:390}]){
  const context=await browser.newContext({viewport,reducedMotion:'reduce'});
  let slow=false;const counts={},errors=[];
  await context.route('**/studio-api/**',async route=>{
   const request=route.request(),url=new URL(request.url());
   counts[url.pathname]=(counts[url.pathname]||0)+1;
   if(slow&&request.method()==='GET')await new Promise(r=>setTimeout(r,2000));
   const response=await context.request.fetch('http://127.0.0.1:8011'+url.pathname+url.search,{method:request.method(),headers:{'Content-Type':'application/json',Authorization:'Bearer local-qa'},data:request.postData()||undefined});
   await route.fulfill({status:response.status(),headers:{'content-type':'application/json','access-control-allow-origin':'*'},body:await response.body()});
  });
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5186/h5/#/pages/studio/manage');
  const current=()=>page.locator('uni-page').filter({visible:true}).last();
  const tab=async text=>current().locator('.admin-native-tabs uni-button').filter({hasText:new RegExp('^'+text+'$')}).click();
  const ready=async title=>{await expect(current().locator('.admin-native-title')).toHaveText(title);await expect(current().locator('.admin-loading')).toHaveCount(0);await expect(current().locator('.admin-error')).toHaveCount(0);};
  await ready('店主工作台');
  await tab('预约管理');await ready('预约管理');
  await current().locator('.admin-filters uni-button').filter({hasText:/^全部$/}).click();
  await expect(current().locator('.admin-booking-card')).toHaveCount(3);
  await tab('顾客消息');await ready('顾客消息');
  await tab('营业状况');await ready('营业状况');
  await current().locator('.admin-filters uni-button').filter({hasText:/^收入$/}).click();
  await expect(current().locator('.admin-filters .chosen').first()).toHaveText('收入');
  await expect.poll(()=>counts['/studio-api/manage/finance']||0).toBeGreaterThanOrEqual(2);
  await page.waitForTimeout(200);
  const scroller=current().locator('.admin-native-body .uni-scroll-view').last();
  await scroller.evaluate(el=>{el.scrollTop=250;el.dispatchEvent(new Event('scroll'));});
  const top=await scroller.evaluate(el=>el.scrollTop);
  await page.waitForTimeout(100);
  slow=true;const baseline={...counts};
  await tab('工作台');await ready('店主工作台');
  await expect(current().locator('.admin-home-metrics')).toBeVisible();
  await tab('营业状况');await ready('营业状况');
  await expect(current().locator('.native-finance-totals')).toBeVisible();
  await expect(current().locator('.admin-filters .chosen').first()).toHaveText('收入');
  await expect.poll(()=>current().locator('.admin-native-body .uni-scroll-view').last().evaluate(el=>el.scrollTop)).toBeGreaterThanOrEqual(Math.max(0,top-3));
  await tab('预约管理');await ready('预约管理');
  await expect(current().locator('.admin-filters .chosen')).toHaveText('全部');
  await expect(current().locator('.admin-booking-card')).toHaveCount(3);
  for(const path of ['/studio-api/manage/desk-summary','/studio-api/manage/reservations','/studio-api/manage/finance'])assert.equal(counts[path],baseline[path],path+' unnecessarily reloaded on a warm tab');
  await tab('营业状况');await ready('营业状况');
  await page.screenshot({path:`${dir}/warm-finance-${viewport.width}x${viewport.height}.png`});
  slow=false;
  await current().locator('.admin-native-actions uni-button').filter({hasText:/增加收入/}).click();
  await ready('增加收入');
  const inputs=current().locator('.admin-native-content .admin-input input');
  const name='Tab cache QA '+viewport.width+' '+Date.now();
  await inputs.nth(0).fill('10.01');await inputs.nth(1).fill(name);await inputs.nth(2).fill('Local cache validation');
  await current().locator('uni-button').filter({hasText:/^现金$/}).click();
  await current().locator('.admin-native-actions uni-button').filter({hasText:/^保存记录$/}).click();
  await ready('编辑记录');
  const before=counts['/studio-api/manage/finance'];slow=true;
  await tab('营业状况');await expect(current().locator('.native-finance-totals')).toBeVisible();
  await expect(current().locator('.admin-loading')).toHaveCount(0);
  await expect.poll(()=>counts['/studio-api/manage/finance']).toBeGreaterThan(before);
  await expect(current().locator('.native-finance-list')).toContainText(name,{timeout:8000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
  assert.deepEqual(errors,[]);
  results.push({viewport,warmTabsNoRequests:true,filterAndScrollPreserved:true,saveInvalidatesCache:true,noOverflow:true});
  slow=false;await context.close();
 }
 await fs.writeFile(`${dir}/checks.json`,JSON.stringify(results,null,2));console.log(JSON.stringify(results));
}finally{await browser.close();}
