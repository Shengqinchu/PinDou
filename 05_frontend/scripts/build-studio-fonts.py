"""Bundle small OFL font subsets in WXSS, so first launch needs no font request."""
import base64
import hashlib
import json
from io import BytesIO
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[2]
target = root / '05_frontend/src/static/studio'
miniapp = json.loads((root / '05_studio/src/content/miniapp.json').read_text('utf-8'))
headings = ''.join(''.join(miniapp[key]) for key in (
    'native_title', 'confirm_title', 'link_title', 'done_title', 'cancelled',
))
for module, key in (('account', 'account'), ('booking-profile', 'title')):
    headings += ''.join(json.loads((root / f'05_studio/src/content/{module}.json').read_text('utf-8'))[key])
for module, keys in {
    'account': ['my_reservations','reservation_title'],
    'profile': ['edit'],
    'miniapp-legal': ['privacy_title','agreement_title'],
    'pages-Home': ['a_little_time_all_yours_9e9d60','make_something_lovely_04db64'],
    'visit-flow': ['experience','time','contact','review'],
    'pages-Details': ['a_little_guide_to_the_studio_1b38da','studio_address_171634','parking_8188de','seats_and_tools_4b0a0a','a_place_to_park_fcb8e3','made_comfortable_made_yours_0c8904','a_few_little_notes_7bbea4'],
    'components-BeadingProcess': ['title','patternTitle','toolsTitle','makingTitle','ironingTitle','finishingTitle'],
    'reservation-cancellation': ['title','contact'],
    'pages-ReservationReceipt': ['the_host_will_confirm_it_ae62ce','your_visit_is_confirmed_94453d','thank_you_for_coming_285672','this_reservation_was_cancelled_54b1d2','see_you_at_the_studio_add3a5','lets_make_again_soon_12f0b9'],
}.items():
    words=json.loads((root / f'05_studio/src/content/{module}.json').read_text('utf-8'))
    headings+=''.join(''.join(words[key]) for key in keys)
font = TTFont(root / 'artifacts/vision3/research/Xiaolai-Regular.ttf')
options = subset.Options()
options.recalc_timestamp = False
cutter = subset.Subsetter(options=options)
cutter.populate(text=headings)
cutter.subset(font)
font.flavor = 'woff2'
buffer = BytesIO()
font.save(buffer)
sources = [
    ('Studio Hand', buffer.getvalue(), 'artifacts/vision3/research/Xiaolai-OFL.txt', '400'),
    ('Studio Serif', (root / '05_studio/node_modules/@fontsource/dm-serif-display/files/dm-serif-display-latin-400-normal.woff2').read_bytes(), '05_studio/node_modules/@fontsource/dm-serif-display/LICENSE', '400'),
    ('Studio Outfit', (root / '05_studio/node_modules/@fontsource-variable/outfit/files/outfit-latin-wght-normal.woff2').read_bytes(), '05_studio/node_modules/@fontsource-variable/outfit/LICENSE', '100 900'),
]
css = ['/* Generated by scripts/build-studio-fonts.py. OFL notices: static/studio/. */']
report = []
for family, data, license_path, weight in sources:
    encoded = base64.b64encode(data).decode('ascii')
    css.append(f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};font-display:swap;src:url("data:font/woff2;base64,{encoded}") format("woff2")}}')
    name = family.lower().replace(' ', '-')
    (target / f'{name}-OFL.txt').write_bytes((root / license_path).read_bytes())
    report.append({'family': family, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()})
(root / '05_frontend/src/static/styles/studio-fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
(target / 'fonts.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
print(json.dumps(report))
